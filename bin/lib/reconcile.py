"""Act 2: evidence that a daily model matches its source.

    bin/reconcile <model>          # prints the checks and writes EVIDENCE.md

Three checks, per day, against raw.raw_events:

  completeness   events in the model vs distinct events in the source
  keys           users in the model vs distinct users in the source
  nulls          null keys in the model

EVIDENCE.md is generated, never written by hand — bin/check-done re-runs
these checks and compares.
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

import duckdb

ROOT = Path.cwd()
GREEN, RED, DIM, RESET = "\033[32m", "\033[31m", "\033[2m", "\033[0m"
TOLERANCE_PCT = 0.5


# --- the three checks ----------------------------------------------------------
# Each returns rows of (day, source_value, model_value). `m` is the model table,
# `d` its date column, `e` its event-count column, `u` its active-user column.


def completeness(con, m: str, d: str, e: str, u: str) -> list[tuple]:
    # TODO: act 2, exercise 2b.
    # Source side: the number of distinct event_id per day in raw.raw_events.
    source_sql = "select null::date as day, null::bigint as n"
    return con.execute(f"""
        with src as ({source_sql}),
             mdl as (select "{d}" as day, sum("{e}") as n from {m} group by 1)
        select coalesce(src.day, mdl.day), src.n, mdl.n
        from src full join mdl on src.day = mdl.day
        where coalesce(src.day, mdl.day) is not null
        order by 1
    """).fetchall()


def keys(con, m: str, d: str, e: str, u: str) -> list[tuple]:
    # TODO: act 2, exercise 2b.
    # Source side: the number of distinct user_id per day in raw.raw_events.
    source_sql = "select null::date as day, null::bigint as n"
    return con.execute(f"""
        with src as ({source_sql}),
             mdl as (select "{d}" as day, sum("{u}") as n from {m} group by 1)
        select coalesce(src.day, mdl.day), src.n, mdl.n
        from src full join mdl on src.day = mdl.day
        where coalesce(src.day, mdl.day) is not null
        order by 1
    """).fetchall()


def nulls(con, m: str, d: str, e: str, u: str) -> list[tuple]:
    # Worked example: a model row with a null day or null counts is a broken row.
    return con.execute(f"""
        select 'all days', 0, count(*) filter (where "{d}" is null or "{e}" is null or "{u}" is null)
        from {m}
    """).fetchall()


CHECKS = [("completeness", completeness), ("keys", keys), ("nulls", nulls)]


# --- plumbing --------------------------------------------------------------------


def find_columns(con, model: str) -> tuple[str, str, str, str]:
    cols = con.execute(
        "select column_name, data_type from information_schema.columns where table_name = ? order by ordinal_position",
        [model],
    ).fetchall()
    if not cols:
        raise SystemExit(f"{RED}no table {model} in the database — build it first: dbt build -s {model}{RESET}")
    date_col = next((c for c, t in cols if t == "DATE"), None)
    event_col = next((c for c, t in cols if "event" in c.lower() and t in ("BIGINT", "INTEGER", "HUGEINT")), None)
    user_col = next((c for c, t in cols if "user" in c.lower() and t in ("BIGINT", "INTEGER", "HUGEINT")), None)
    if not (date_col and event_col and user_col):
        raise SystemExit(f"{RED}{model}: need a DATE column, an event-count column and a user-count column{RESET}")
    schema = con.execute("select table_schema from information_schema.tables where table_name = ?", [model]).fetchone()[0]
    return f'"{schema}"."{model}"', date_col, event_col, user_col


def is_off(src, mdl) -> bool:
    if src is None or mdl is None:
        return True
    if src == 0:
        return mdl != 0
    return abs(100.0 * (mdl - src) / src) > TOLERANCE_PCT


def session_settings() -> dict:
    """The warehouse session settings dbt uses (profiles.yml) — evidence must run in the same session."""
    try:
        import yaml
        prof = yaml.safe_load((ROOT / "profiles.yml").read_text())
        name = next(iter(prof))
        out = prof[name]["outputs"][prof[name].get("target", "dev")]
        return out.get("settings") or {}
    except Exception:
        return {}


def run_checks(model: str, db: Path) -> list[tuple[str, list[tuple]]]:
    con = duckdb.connect(str(db), read_only=True)
    for key, value in session_settings().items():
        con.execute(f"SET {key} = '{value}'")
    try:
        cols = find_columns(con, model)
        return [(name, fn(con, *cols)) for name, fn in CHECKS]
    finally:
        con.close()


def render(model: str, results: list[tuple[str, list[tuple]]]) -> tuple[str, bool]:
    lines = [f"# Evidence: {model}", "", "Generated by `bin/reconcile`. Do not edit — `bin/check-done` re-runs it.", ""]
    all_ok = True
    for name, rows in results:
        bad = [r for r in rows if is_off(r[1], r[2])]
        ok = bool(rows) and not bad
        all_ok &= ok
        lines.append(f"## {name}: {'PASS' if ok else 'FAIL'} ({len(rows) - len(bad)} of {len(rows)} rows within {TOLERANCE_PCT}%)")
        lines.append("")
        lines.append("| day | source | model |")
        lines.append("|---|---:|---:|")
        for day, src, mdl in rows:
            flag = " ✗" if is_off(src, mdl) else ""
            lines.append(f"| {day} | {src if src is not None else '—'} | {mdl if mdl is not None else '—'}{flag} |")
        lines.append("")
    lines.append(f"**Result: {'PASS' if all_ok else 'FAIL'}**")
    return "\n".join(lines) + "\n", all_ok


def main() -> int:
    if len(sys.argv) != 2:
        print("usage: bin/reconcile <model>")
        return 2
    model = sys.argv[1]
    db = ROOT / os.environ.get("DEMO_DB", "demo.duckdb")
    results = run_checks(model, db)
    text, ok = render(model, results)
    (ROOT / "EVIDENCE.md").write_text(text)
    for name, rows in results:
        bad = [r for r in rows if is_off(r[1], r[2])]
        colour = GREEN if rows and not bad else RED
        print(f"{colour}{name:13} {len(rows) - len(bad)} of {len(rows)} rows within {TOLERANCE_PCT}%{RESET}")
        for day, src, mdl in bad[:5]:
            print(f"  {DIM}{day}: source {src}, model {mdl}{RESET}")
        if len(bad) > 5:
            print(f"  {DIM}… {len(bad) - 5} more{RESET}")
    print(f"\n{GREEN if ok else RED}{'PASS' if ok else 'FAIL'}{RESET} · written to EVIDENCE.md")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
